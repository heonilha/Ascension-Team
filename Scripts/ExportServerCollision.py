# Export the CombatLab blocking geometry as a 2D collision map for the game server.
#
# Run (does not modify or save the map):
#   UnrealEditor-Cmd.exe <project>.uproject -run=pythonscript -script=<repo>\Scripts\ExportServerCollision.py -unattended -nullrhi -nosplash
#
# Output: Data/ServerCollision/CombatLab.txt (copy it to the server repository's data/ folder unchanged).
# Every collidable static mesh actor becomes a convex polygon in the XY plane plus its Z range.
# Cubes become rotated rectangles, cylinders ellipses sampled with 24 vertices. Spheres become circles of the
# smallest scaled radius, because physics cannot stretch a sphere (CoverRock 2.2x2.7x1.9 collides as r=95).
# The server treats an obstacle as blocking when its top is above the character's step height.
#
# Verification runs in the game, where physics is live (editor commandlet worlds have no physics state):
#   UnrealEditor-Cmd.exe <project>.uproject -game -nullrhi -unattended -nosplash -AscensionCollisionVerify
# It compares real capsule overlaps with this file on a 40 cm grid (Source/AscensionPrototype/CLCollisionVerify.cpp).
import math
import os
import unreal

MAP_PATH = '/Game/Maps/CombatLab'
HALF_WIDTH, HALF_DEPTH = 2800.0, 2400.0
STEP_HEIGHT = 45.0           # UCharacterMovementComponent default MaxStepHeight
ELLIPSE_VERTICES = 24

levels = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
if not levels.load_level(MAP_PATH):
    raise RuntimeError('Cannot open ' + MAP_PATH)


def rotate(x, y, yaw_degrees):
    c, s = math.cos(math.radians(yaw_degrees)), math.sin(math.radians(yaw_degrees))
    return x * c - y * s, x * s + y * c


def collision_extent(shape, scale):
    """Half extents (x, y, z) of the physics shape. Engine basic shapes are 100 cm across.
    A sphere's simple collision cannot stretch: physics scales it uniformly by the smallest axis."""
    if shape == 'Sphere':
        r = 50.0 * min(abs(scale.x), abs(scale.y), abs(scale.z))
        return r, r, r
    return 50.0 * scale.x, 50.0 * scale.y, 50.0 * scale.z


def shape_polygon(shape, hx, hy, yaw):
    if shape == 'Cube':
        corners = [(-hx, -hy), (hx, -hy), (hx, hy), (-hx, hy)]
    else:  # Cylinder (axis Z) and Sphere: ellipse/circle in XY
        corners = [(hx * math.cos(i * math.tau / ELLIPSE_VERTICES), hy * math.sin(i * math.tau / ELLIPSE_VERTICES))
                   for i in range(ELLIPSE_VERTICES)]
    return [rotate(x, y, yaw) for x, y in corners]


obstacles = []
for actor in actors.get_all_level_actors():
    if not isinstance(actor, unreal.StaticMeshActor):
        continue
    component = actor.static_mesh_component
    if component.get_collision_enabled() == unreal.CollisionEnabled.NO_COLLISION:
        continue
    mesh = component.static_mesh
    shape = mesh.get_name() if mesh else ''
    if shape not in ('Cube', 'Cylinder', 'Sphere'):
        raise RuntimeError('Unsupported collision mesh %s on %s' % (shape, actor.get_actor_label()))
    label = actor.get_actor_label()
    location, rotation, scale = actor.get_actor_location(), actor.get_actor_rotation(), actor.get_actor_scale3d()
    if abs(rotation.pitch) > .01 or abs(rotation.roll) > .01:
        raise RuntimeError('Tilted collider is not supported in 2D: ' + label)
    if label == 'Open_Ground':
        continue  # the walking surface itself
    hx, hy, hz = collision_extent(shape, scale)
    z_min, z_max = location.z - hz, location.z + hz
    polygon = [(location.x + x, location.y + y) for x, y in shape_polygon(shape, hx, hy, rotation.yaw)]
    obstacles.append({'name': label, 'z_min': z_min, 'z_max': z_max, 'polygon': polygon,
                      'blocking': z_max > STEP_HEIGHT})

obstacles.sort(key=lambda o: o['name'])
root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
out_dir = os.path.join(root, 'Data', 'ServerCollision')
os.makedirs(out_dir, exist_ok=True)
out_path = os.path.join(out_dir, 'CombatLab.txt')
with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Ascension server collision map. Generated by Scripts/ExportServerCollision.py from /Game/Maps/CombatLab.\n')
    f.write('# Do not edit by hand: re-run the exporter after changing the map.\n')
    f.write('# obstacle <name> <blocking 0|1> <z_min> <z_max> <vertex count> <x y>... (cm, counter-clockwise convex polygon)\n')
    f.write('version 1\n')
    f.write('map CombatLab\n')
    f.write('bounds %.1f %.1f %.1f %.1f\n' % (-HALF_WIDTH, -HALF_DEPTH, HALF_WIDTH, HALF_DEPTH))
    f.write('step_height %.1f\n' % STEP_HEIGHT)
    for o in obstacles:
        coords = ' '.join('%.1f %.1f' % (x, y) for x, y in o['polygon'])
        f.write('obstacle %s %d %.1f %.1f %d %s\n' % (o['name'], 1 if o['blocking'] else 0, o['z_min'], o['z_max'],
                                                     len(o['polygon']), coords))
blocking = [o for o in obstacles if o['blocking']]
unreal.log('ASCENSION_COLLISION_EXPORT obstacles=%d blocking=%d path=%s' % (len(obstacles), len(blocking), out_path))

